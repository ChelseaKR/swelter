def cmd_ingest_serve(args: argparse.Namespace) -> int:
    """Run the authenticated node write path: a write-only listener, per-node HMAC keys.

    Kept out of ``swelter serve`` on purpose — the public read surface and the node write
    surface are different trust boundaries and stay in different processes.
    """
    keys_path = Path(args.keys)
    if not keys_path.is_file():
        _err(f"swelter: keys file {args.keys} not found")
        _err(f"  issue one key per node first:  swelter node-key <node_id> --keys {args.keys}")
        return 1
    try:
        keys = ingest_server.load_keys(keys_path)
    except ingest_server.KeyfileError as exc:
        _err(f"swelter: {exc}")
        return 1
    if not keys:
        _err(f"swelter: keys file {args.keys} holds no node keys; issue them with swelter node-key")
        return 1
    paths = store_paths(args.store)
    if (paths["dir"] / snapshot.SOURCE_METADATA_FILENAME).is_file():
        _err("swelter: refusing to mix node ingest with a fetched third-party store")
        return 1
    store = open_store(args.store)
    ctx = ingest_server.IngestServerContext(
        store=store,
        keys=keys,
        quarantine_path=paths["quarantine"],
        skew_s=args.skew,
    )
    base = f"http://{args.host}:{args.port}"
    route = ingest_server.INGEST_ROUTE
    _err(f"swelter: ingest listener (write-only, per-node HMAC) at {base}{route}")
    _err(
        f"  {len(keys)} node key(s) from {args.keys} · replay window ±{int(args.skew)}s · "
        f"auth failures → {paths['quarantine']}  (Ctrl-C to stop)"
    )
    try:
        ingest_server.serve(ctx, host=args.host, port=args.port)
    finally:
        store.close()
    return 0


def cmd_node_key(args: argparse.Namespace) -> int:
    """Issue (or rotate) a node's ingest key into the operator-local keys file.

    Prints the key to stdout — the one moment it is visible — for the operator to copy into the
    node's uncommitted ``config.py``. Who gets a key, and when one is rotated or revoked, is a
    collective decision (docs/governance.md); this command is just the mechanism.
    """
    try:
        key = ingest_server.issue_key(Path(args.keys), args.node_id)
    except ingest_server.KeyfileError as exc:
        _err(f"swelter: {exc}")
        return 1
    _err(f"swelter: issued ingest key for {args.node_id} → {args.keys} (owner-only, mode 0600)")
    _err("  copy the key below into the node's uncommitted config.py as `ingest_key`.")
    _err("  never commit it, never put it in network.yaml, never publish the keys file;")
    _err("  re-running this command for the same node rotates (replaces) the key.")
    print(key)
    return 0


def _print_node_preview(node: NodeConfig, config: NetworkConfig) -> None:
    """Print what the map/API publishes for one node, versus its private exact coordinate."""
    label = f" ({node.label})" if node.label else ""
    print(f"node {node.node_id}{label}")
    if node.lat is None or node.lon is None:
        print("  not placed — publishes nothing (no location on record)")
        print()
        return
    print(f"  your private coordinate — never published: {node.lat:.6f}, {node.lon:.6f}")
    published = cast(tuple[float, float], node.public_location(config.grid_resolution_m))
    cell_id, cell_label = aggregate.node_cell_map(config).get(node.node_id, ("", ""))
    label_suffix = f" ({cell_label})" if cell_label else ""
    print(f"  published coordinate: {published[0]:.6f}, {published[1]:.6f}")
    print(f"  published cell: {cell_id}{label_suffix}")
    offset_m = haversine_m(node.lat, node.lon, published[0], published[1])
    print(f"  map shows a point ~{offset_m:.0f} m from your sensor")
    print(f"  location mode: {node.location}")
    if node.location == "precise":
        print(
            "  ⚠ WARNING: location is 'precise' — your EXACT coordinate is published as-is. "
            "Coarse-by-default grid-snap protection is OFF for this node. Switch `location` "
            "back to 'coarse' in network.yaml to publish only the grid cell."
        )
    print()


def cmd_node_preview(args: argparse.Namespace) -> int:
    """Show a host exactly what the map/API publishes for their node(s).

    Read-only and host-facing: it never changes a node's location or its published mode, it
    just makes visible — in the host's own terminal — the same coordinate the map and API
    already publish, so "coarse by default" is a fact a host can verify, not just a promise.
    """
    config = _load_config(args.config)
    if args.node_id:
        node = config.node(args.node_id)
        if node is None:
            _err(f"swelter: node {args.node_id} not found in {args.config}")
            return 1
        _print_node_preview(node, config)
        return 0
    if not config.nodes:
        _err(f"swelter: no nodes registered in {args.config}")
        return 0
    for node in config.nodes:
        _print_node_preview(node, config)
    return 0


