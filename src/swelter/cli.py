def cmd_ingest(args: argparse.Namespace) -> int:
    if not Path(args.input).is_file():
        _err(f"swelter: input {args.input} not found")
        return 1
    paths = store_paths(args.store)
    if (paths["dir"] / snapshot.SOURCE_METADATA_FILENAME).is_file():
        _err("swelter: refusing to mix native ingest with a fetched third-party store")
        return 1
    manifest = obs.RunManifest()
    with open_store(args.store) as store:
        result = ingest.ingest_file(args.input, store, quarantine_path=paths["quarantine"])
    manifest.record(
        "ingest",
        "payloads ingested",
        payloads_accepted=result.accepted_payloads,
        payloads_quarantined=result.quarantined,
    )
    manifest.finish()
    obs.write_manifest(paths["dir"], manifest)
    _err(
        f"swelter: ingested {result.accepted_payloads} payloads → "
        f"{result.observations_written} new observations "
        f"({result.duplicates} duplicates, {result.quarantined} quarantined)"
    )
    return 0


def _print_calibration_status(calibration: dict[str, Any]) -> None:
    """Print the correction-drift summary and any aging corrections to stderr (human ``qc``).

    Descriptive only: it reports how old a correction's evidence is, never changing a value or its
    calibration state (hard rule #3), and never ranking neighborhoods."""
    summary = cast(dict[str, Any], calibration["summary"])
    _err(
        f"swelter: calibration — {summary['aging']}/{summary['corrections']} corrections aging "
        f"past the {cast(float, calibration['horizon_days']):.0f}-day drift horizon"
    )
    for c in cast(list[dict[str, Any]], calibration["corrections"]):
        if c["aging"]:
            _err(
                f"  aging correction  {c['version']}  "
                f"(window_end {c['window_end']}, {c['age_days']:.0f}d old)"
            )


def _qc_json_payload(
    health: list[qc.NodeHealth],
    gaps: list[qc.Gap],
    coverage: dict[str, object],
    calibration: dict[str, object] | None,
    twins: list[qc.TwinAgreement],
) -> dict[str, Any]:
    """The ``swelter qc --json`` payload: node health, gaps, coverage, and the optional side
    blocks — correction-drift ``calibration`` (FIX-03, absent without a registry) and the
    ``twin_agreement`` cross-check (EXP-09, absent without configured twins)."""
    payload: dict[str, Any] = {
        "nodes": [
            {
                "node_id": n.node_id,
                "status": n.status,
                "observations": n.observations,
                "completeness": n.completeness,
                "flagged_fraction": round(n.flagged_fraction, 3),
                "online": n.online,
                "last_seen": n.last_seen,
            }
            for n in health
        ],
        "gaps": [
            {
                "node_id": g.node_id,
                "parameter": g.parameter,
                "start": g.start,
                "end": g.end,
                "minutes": round(g.seconds / 60),
            }
            for g in gaps
        ],
        "coverage_equity": coverage,
    }
    if calibration is not None:
        payload["calibration"] = calibration
    if twins:
        payload["twin_agreement"] = qc.twin_agreement_json(twins)
    return payload


def cmd_qc(args: argparse.Namespace) -> int:
    config = _load_config(args.config)
    paths = store_paths(args.store)
    with open_store(args.store) as store:
        raw = store.read(calibration=RAW)
        all_obs = list(store.all())
    if not raw:
        _err("swelter: store is empty")
        return 0
    latest = max(o.timestamp for o in raw)
    gaps = qc.detect_gaps(raw, args.interval)
    health = qc.node_health(
        raw, latest, offline_after_s=args.interval * 3, expected_interval_s=args.interval
    )
    # Coverage-equity: calibrated-vs-raw node counts per published cell, so an under-calibrated
    # block is visible rather than hidden behind the network average (audit B3). Descriptive
    # coverage, not a ranking of neighborhoods (see qc.coverage_equity / docs/RESEARCH-ROADMAP).
    coverage = qc.coverage_equity(all_obs, aggregate.node_cell_map(config))
    cov = cast(dict[str, Any], coverage["summary"])
    # Correction-drift surveillance: each calibrated node/parameter's correction age vs the latest
    # reading, flagged past the drift horizon (FIX-03). Descriptive only — reads window_end, never
    # changes a value or a calibration state (hard rule #3). Absent when no registry is on disk.
    registry = (
        calibrate.CorrectionRegistry.from_yaml(paths["registry"])
        if paths["registry"].is_file()
        else calibrate.CorrectionRegistry()
    )
    calibration = qc.calibration_block(raw, registry) if len(registry) else None
    # Cross-checked precision tier (EXP-09): how tightly configured sensor twins agree over their
    # window — a drift smoke-alarm, never a promotion. QC/health metadata only; every reading stays
    # raw/provisional (hard rule #3). Empty when no twin_windows are configured, so the output is
    # unchanged for a network that never registers a twin pair.
    twins = qc.twin_agreement(raw, config.twin_windows) if config.twin_windows else []
    if args.json:
        print(json.dumps(_qc_json_payload(health, gaps, coverage, calibration, twins), indent=2))
        return 0
    not_ok = sum(1 for n in health if n.status != "ok")
    _err(
        f"swelter: {len(health)} nodes ({not_ok} degraded/offline), {len(gaps)} gaps "
        f"over interval {int(args.interval)}s"
    )
    for gap in gaps[:10]:
        _err(
            f"  gap  {gap.node_id}/{gap.parameter}  {gap.start} → {gap.end}  "
            f"({round(gap.seconds / 60)} min)"
        )
    for node in health:
        _err(
            f"  {node.node_id:>10}  {node.status.upper():<8}  {node.observations:>6} obs  "
            f"{node.completeness * 100:5.1f}% complete  {node.flagged_fraction * 100:5.1f}% flagged"
        )
    if calibration is not None:
        _print_calibration_status(calibration)
    _err(
        f"swelter: coverage — {cov['calibrated_nodes']}/{cov['nodes']} nodes calibrated, "
        f"{cov['confirmed_cells']}/{cov['cells']} cells confirmed, "
        f"{cov['provisional_cells']} provisional cell(s)"
    )
    for cell in cast(list[dict[str, Any]], coverage["cells"]):
        if not cell["confirmed"]:
            name = cell["label"] or cell["cell_id"]
            _err(
                f"  provisional cell  {name}  "
                f"({cell['calibrated_nodes']}/{cell['nodes']} calibrated)"
            )
    if twins:
        diverged = sum(1 for t in twins if t.status == "diverged")
        _err(
            f"swelter: twin cross-check — {len(twins)} pair(s), {diverged} diverged "
            f"(precision only; cross-checked ≠ calibrated — see docs/calibration.md)"
        )
        for t in twins:
            comparator = "≤" if t.residual_spread <= t.agreement_threshold else ">"
            _err(
                f"  {t.status.upper():<17}  {t.node_a}/{t.node_b} {t.parameter}  "
                f"spread {t.residual_spread} {comparator} {t.agreement_threshold} "
                f"({t.n_pairs} pairs)"
            )
    return 0


def cmd_status(args: argparse.Namespace) -> int:
    """The steward console: a ranked, evidence-cited "what needs doing" list.

    Composes signals the pipeline already produces — node health/liveness, correction age
    (FIX-03), coverage-equity — into one ranked plan (EXP-05). Nothing here fetches or computes a
    new number; ``steward.plan`` is a pure function over the same reports ``qc`` prints.
    """
    config = _load_config(args.config)
    paths = store_paths(args.store)
    with open_store(args.store) as store:
        raw = store.read(calibration=RAW)
        all_obs = list(store.all())
    if not raw:
        _err("swelter: store is empty")
        if args.json:
            empty = {"generated_for": "", "actions": [], "disclaimer": steward.DISCLAIMER}
            print(json.dumps(empty, indent=2))
        return 0
    latest = max(o.timestamp for o in raw)
    coverage = qc.coverage_equity(all_obs, aggregate.node_cell_map(config))

    if paths["registry"].is_file():
        registry = calibrate.CorrectionRegistry.from_yaml(paths["registry"])
    else:
        registry = calibrate.CorrectionRegistry()

    # The health report carries the correction-drift block when a registry is on disk, so the same
    # descriptive correction-age signal the steward plan ranks (correction_expired/expiring) also
    # sits in the health dict the plan is built from. Descriptive only — no value or calibration
    # state changes (hard rule #3).
    health = qc.health_report(
        raw,
        expected_interval_s=args.interval,
        coverage=coverage,
        registry=registry if len(registry) else None,
    )

    result = steward.plan(health, coverage, registry.all(), latest=latest)

    if args.json:
        print(json.dumps(result, indent=2))
        return 0

    actions = cast(list[dict[str, Any]], result["actions"])
    _err(f"swelter: steward plan for {result['generated_for']} — {len(actions)} action(s)")
    for i, action in enumerate(actions, start=1):
        _err(f"  {i:>2}. [{action['kind']}] {action['reason']}")
    _err(f"swelter: {result['disclaimer']}")
    return 0


def cmd_calibrate(args: argparse.Namespace) -> int:
    if not Path(args.colocation).is_file():
        _err(f"swelter: colocation {args.colocation} not found")
        return 1
    config = _load_config(args.config)
    pairs = calibrate.read_colocation(args.colocation)
    registry = calibrate.fit(pairs, models=_node_models(config))
    paths = store_paths(args.store)
    registry.to_yaml(paths["registry"])
    _err(f"swelter: fit {len(registry)} corrections → {paths['registry']}")
    width = max((len(c.version) for c in registry.all()), default=0)
    for c in registry.all():
        # The version now carries the fit's identity after "@", so it is longer than the old
        # fixed 28-character column could hold; align on the widest one actually being printed.
        _err(f"  {c.version:<{width}} n={c.n:<4} R²={c.r2:.3f}  ±{c.residual_std} {c.parameter}")
    manifest = obs.RunManifest()
    if not args.fit_only:
        with open_store(args.store) as store:
            raw = store.read(calibration=RAW)
            store.drop_calibrated()
            calibrated = [o for o in calibrate.apply(raw, registry) if o.calibration != RAW]
            written = store.write(calibrated)
        manifest.record(
            "calibrate",
            "corrections applied",
            corrections_applied=written.written,
            corrections_skipped_stale=_corrections_skipped_stale(raw, registry, calibrated),
        )
        _err(f"swelter: applied corrections → {written.written} calibrated observations")
    manifest.finish()
    obs.write_manifest(paths["dir"], manifest)
    return 0


def _monitor_bbox(
    args: argparse.Namespace, *, pad: float = 0.1
) -> tuple[float, float, float, float] | None:
    """A small AirNow bounding box around the reference monitor's published coordinates.

    Regulatory monitors are public record, so their coordinates live in ``network.yaml`` under
    ``reference_monitors:`` (``ReferenceMonitor.lat``/``lon``). A live fetch needs them to scope the
    query; ``None`` (after a diagnostic) when they are absent, steering the operator to a fixture.
    """
    config = _load_config(args.config)
    monitor = next((m for m in config.reference_monitors if m.monitor_id == args.monitor), None)
    if monitor is None or monitor.lat is None or monitor.lon is None:
        _err(
            f"swelter: no coordinates for monitor {args.monitor} in {args.config}; add lat/lon "
            "under reference_monitors: or pass --reference-fixture for an offline run"
        )
        return None
    return (monitor.lon - pad, monitor.lat - pad, monitor.lon + pad, monitor.lat + pad)


def _colocate_reference_series(
    args: argparse.Namespace, start: str, end: str, parameter: str
) -> list[Any] | None:
    """The reference series for ``colocate``: a committed fixture (offline) or live AirNow fetch.

    ``None`` (after a diagnostic) when a live fetch is requested without a key or monitor
    coordinates, or when the fixture cannot be parsed. The key is read from ``--api-key`` or
    ``AIRNOW_API_KEY`` and never echoed.
    """
    from .sources import airnow
    from .sources._http import SourceError

    if args.reference_fixture:
        try:
            payload = json.loads(Path(args.reference_fixture).read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            _err(f"swelter: cannot read --reference-fixture {args.reference_fixture}: {exc}")
            return None
        return airnow.parse_series(payload, parameter=parameter)

    api_key = args.api_key or os.environ.get("AIRNOW_API_KEY", "")
    if not api_key:
        _err(
            "swelter: live reference fetch needs --api-key or AIRNOW_API_KEY "
            "(or pass --reference-fixture for an offline run)"
        )
        return None
    bbox = _monitor_bbox(args)
    if bbox is None:
        return None
    try:
        return airnow.fetch(
            args.monitor, api_key, start=start[:13], end=end[:13], bbox=bbox, parameter=parameter
        )
    except SourceError as exc:
        _err(f"swelter: AirNow fetch failed: {exc}")
        return None


def cmd_colocate(args: argparse.Namespace) -> int:
    """EXP-02: build co-location training pairs from stored raw node data and a reference series.

    Emits ``TrainingPair``s in ``calibrate.read_colocation`` format (plus the reference ``monitor``
    id), matching each hourly reference reading to the nearest node sample within ``--tolerance-s``
    (see :mod:`swelter.colocate`). The reference series comes from a committed fixture
    (``--reference-fixture``, offline) or a live AirNow fetch (``--api-key``/``AIRNOW_API_KEY``);
    its own license and attribution travel to stderr so the reference's rights are never dropped.
    The monitor's AQS id flows into ``Correction.reference`` when the emitted pairs are later fit.
    """
    from .sources import airnow

    if ".." not in args.window:
        _err('swelter: --window expects "START..END" ISO-8601 timestamps')
        return 1
    start_s, _, end_s = args.window.partition("..")
    start_s, end_s = start_s.strip(), end_s.strip()
    try:
        start_e, end_e = colocate._epoch(start_s), colocate._epoch(end_s)
    except ValueError:
        _err("swelter: --window timestamps must be ISO-8601 (e.g. 2026-06-01T00:00:00Z)")
        return 1
    if end_e < start_e:
        _err("swelter: --window end is before its start")
        return 1
    parameter = args.parameter

    with open_store(args.store) as store:
        node_raw = store.read(node_id=args.node, parameter=parameter, calibration=RAW)
        humidity_raw = store.read(node_id=args.node, parameter="humidity_pct", calibration=RAW)
    node_samples = [
        colocate.Sample(o.timestamp, o.value)
        for o in node_raw
        if o.qc not in QC_REJECTED and start_e <= colocate._epoch(o.timestamp) <= end_e
    ]
    humidity = {o.timestamp: o.value for o in humidity_raw if o.qc not in QC_REJECTED}

    readings = _colocate_reference_series(args, start_s, end_s, parameter)
    if readings is None:
        return 1
    readings = [r for r in readings if r.monitor_id == args.monitor]
    pairs = colocate.pair_reference(
        args.node,
        parameter,
        node_samples,
        colocate.reference_samples(readings),
        tolerance_s=args.tolerance_s,
        humidity=humidity,
        monitor=args.monitor,
    )

    lines = "\n".join(json.dumps(colocate.training_pair_to_row(p)) for p in pairs)
    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(lines + "\n" if lines else "", encoding="utf-8")
    elif lines:
        print(lines)

    _err(
        f"swelter colocate: {len(pairs)} pair(s) for {args.node}/{parameter} vs "
        f"monitor {args.monitor}" + (f" → {args.out}" if args.out else "")
    )
    _err(f"  reference source: {airnow.SOURCE}; license: {airnow.LICENSE}")
    _err(f"  {airnow.ATTRIBUTION}")
    return 0


def cmd_aggregate(args: argparse.Namespace) -> int:
    config = _load_config(args.config)
    paths = store_paths(args.store)
    with open_store(args.store) as store:
        surface = aggregate.aggregate(store.all(), config)
    out = Path(args.out or paths["aggregate"])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(surface.snapshot_geojson(), indent=2), encoding="utf-8")
    manifest = obs.RunManifest()
    manifest.record(
        "aggregate",
        "surface built",
        cells_built=len(surface.cells),
        cells_provisional=sum(1 for c in surface.cells if c.provisional),
    )
    manifest.finish()
    obs.write_manifest(paths["dir"], manifest)
    _err(f"swelter: {len(surface.cells)} cell-hours → {out}")
    return 0


def cmd_alerts(args: argparse.Namespace) -> int:
    """Build the neighborhood heat/AQI alerts feed (JSON + Atom) from the current surface."""
    config = _load_config(args.config)
    with open_store(args.store) as store:
        observations = list(store.all())
        surface = aggregate.aggregate(observations, config)
    feed = alerts.build_feed(
        surface,
        network=config.name,
        base_url=args.base_url,
        thresholds=config.alert_thresholds or None,
        pack=hazard_packs.resolve_pack(config.hazard_pack),
    )
    if args.format == "atom":
        sys.stdout.write(feed.to_atom())
    elif args.format == "json":
        sys.stdout.write(json.dumps(feed.to_json(), indent=2) + "\n")
    if args.web:
        try:
            terms = snapshot.load_data_terms(Path(args.store), observations=observations)
        except ValueError as exc:
            _err(f"swelter alerts: data provenance is invalid ({exc}); refusing to publish")
            return 1
        _write_web_alerts(Path(args.web), surface, config, data_terms=terms)
        _err(f"swelter: wrote alerts.json + alerts.xml + alerts.es.xml → {args.web}/")
    _err(f"swelter: {len(feed.alerts)} active alert(s) at {feed.bucket or 'no data'}")
    return 0


